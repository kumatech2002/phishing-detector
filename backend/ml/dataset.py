# ---------------------------------------------------------------------------
# Phishing attack pattern generators
# ---------------------------------------------------------------------------

RISKY_TLDS = [".xyz", ".top", ".info", ".biz", ".tk", ".online",
              ".site", ".live", ".click", ".cc", ".net", ".org"]
SUSPICIOUS_WORDS = ["secure", "login", "verify", "account", "online",
                    "pay", "update", "support", "portal", "mobile",
                    "internet", "alert", "confirm", "transfer", "reset"]


def _char_swap(s: str, rng: random.Random) -> str:
    """Swap two adjacent characters."""
    if len(s) < 3:
        return s
    i = rng.randint(0, len(s) - 2)
    return s[:i] + s[i + 1] + s[i] + s[i + 2:]


def _char_insert(s: str, rng: random.Random) -> str:
    """Insert a random letter at a random position."""
    i = rng.randint(0, len(s))
    ch = rng.choice("abcdefghijklmnopqrstuvwxyz")
    return s[:i] + ch + s[i:]


def _char_delete(s: str, rng: random.Random) -> str:
    """Delete a random character."""
    if len(s) < 3:
        return s
    i = rng.randint(0, len(s) - 1)
    return s[:i] + s[i + 1:]


def _char_replace(s: str, rng: random.Random) -> str:
    """Replace a character with a visually similar one (homoglyph)."""
    homoglyphs = {
        "a": "4", "e": "3", "i": "1", "o": "0", "l": "1",
        "s": "5", "g": "9", "b": "6", "t": "7",
    }
    candidates = [(i, h) for i, c in enumerate(s) if c in homoglyphs
                  for h in [homoglyphs[c]]]
    if not candidates:
        return s + rng.choice("0123456789")
    i, h = rng.choice(candidates)
    return s[:i] + h + s[i + 1:]


def _hyphen_keyword(bank: str, rng: random.Random) -> str:
    """accessbank-secure-login.com style."""
    kws = rng.sample(SUSPICIOUS_WORDS, k=rng.randint(1, 2))
    tld = rng.choice([".com", ".net", ".org"])
    return "-".join([bank] + kws) + tld


def _subdomain_camouflage(bank: str, rng: random.Random) -> str:
    """gtbank.verify-account.com style."""
    kws = rng.sample(SUSPICIOUS_WORDS, k=rng.randint(1, 2))
    suffix = "-".join(kws)
    tld = rng.choice([".com", ".net", ".info"])
    return f"{bank}.{suffix}{tld}"


def _risky_tld_swap(bank: str, rng: random.Random) -> str:
    """gtbank.xyz style."""
    tld = rng.choice(RISKY_TLDS)
    return bank + tld


def _random_suffix(bank: str, rng: random.Random) -> str:
    """gtbank91823.com style."""
    suffix = "".join([str(rng.randint(0, 9)) for _ in range(rng.randint(3, 6))])
    tld = rng.choice([".com", ".net", ".online"])
    return bank + suffix + tld


def _keyword_prefix(bank: str, rng: random.Random) -> str:
    """secure-gtbank.com style."""
    kw = rng.choice(SUSPICIOUS_WORDS)
    tld = rng.choice([".com", ".net"])
    return f"{kw}-{bank}{tld}"


ATTACK_GENERATORS = [
    lambda b, rng: _char_swap(b, rng) + rng.choice([".com", ".net", ".xyz"]),
    lambda b, rng: _char_insert(b, rng) + rng.choice([".com", ".net", ".online"]),
    lambda b, rng: _char_delete(b, rng) + rng.choice([".com", ".info"]),
    lambda b, rng: _char_replace(b, rng) + rng.choice([".com", ".xyz"]),
    _hyphen_keyword,
    _subdomain_camouflage,
    _risky_tld_swap,
    _random_suffix,
    _keyword_prefix,
]


def generate_phishing_domains(target_count: int, rng: random.Random) -> List[str]:
    """Generate phishing domain strings."""
    domains = []
    bank_names = NIGERIAN_BANKS[:]
    # Also include shorter aliases
    bank_names += ["access", "gtb", "firstb", "zenith", "fidelity",
                   "union", "eco", "stanbic", "ibtc", "polaris"]
    seen = set()
    attempts = 0
    while len(domains) < target_count and attempts < target_count * 20:
        bank = rng.choice(bank_names)
        gen = rng.choice(ATTACK_GENERATORS)
        try:
            d = gen(bank, rng).lower().strip()
        except Exception:
            attempts += 1
            continue
        if d and d not in seen and len(d) > 4:
            seen.add(d)
            domains.append(d)
        attempts += 1
    return domains


# ---------------------------------------------------------------------------
# Dataset assembly
# ---------------------------------------------------------------------------

def build_dataset(output_path: Path, seed: int = RANDOM_SEED) -> Path:
    """
    Build the labelled dataset CSV and write it to ``output_path``.

    Returns the path to the written file.
    """
    rng = random.Random(seed)

    legitimate = list(set(LEGITIMATE_DOMAINS))  # deduplicate
    # Extend legitimate set with more realistic variations
    extra_legit = []
    for d in LEGITIMATE_DOMAINS:
        base = d.split(".")[0] if not d.startswith("www") else ".".join(d.split(".")[1:3])
        for subdomain in ["api", "app", "m", "mobile", "internet", "ibank", "webbank"]:
            extra_legit.append(f"{subdomain}.{base}.com.ng")
            extra_legit.append(f"{subdomain}.{base}.com")
    legitimate = list(set(legitimate + extra_legit))
    rng.shuffle(legitimate)

    # Target ~60% phishing, ~40% legitimate for a realistic imbalance
    n_legit = len(legitimate)
    n_phish = max(int(n_legit * 1.5), 3000)

    phishing = generate_phishing_domains(n_phish, rng)

    feature_names = get_feature_names()
    output_path.parent.mkdir(parents=True, exist_ok=True)

    rows = []
    for domain in legitimate:
        feats = extract_features(domain)
        row = {k: feats[k] for k in feature_names}
        row["domain"] = domain
        row["label"] = 0
        rows.append(row)

    for domain in phishing:
        feats = extract_features(domain)
        row = {k: feats[k] for k in feature_names}
        row["domain"] = domain
        row["label"] = 1
        rows.append(row)

    rng.shuffle(rows)

    fieldnames = ["domain"] + feature_names + ["label"]
    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"[dataset] Wrote {len(rows)} rows ({n_legit} legitimate, {len(phishing)} phishing) -> {output_path}")
    return output_path


