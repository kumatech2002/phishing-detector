"""
dataset.py — Synthetic labelled dataset generator for Nigerian bank phishing detection.

This module generates a reproducible, seed-fixed dataset of ~5,000 domain records
labelled as legitimate (0) or phishing (1).

Dataset provenance
------------------
This is a programmatically-generated synthetic benchmark dataset. It is NOT a
scrape of real phishing feeds. The legitimate seed domains are the publicly-known
base domains of ten major Nigerian banks. The phishing samples are generated by
applying eight realistic attack patterns (typosquatting, homoglyph substitution,
subdomain camouflage, hyphenation, TLD swapping, keyword stuffing, random-suffix,
and multi-technique combinations) to those seed names.

Running this script produces identical output on any machine because the random
seed is fixed. To supplement with real-world data, export the CSV and append
rows from threat-intelligence feeds such as PhishTank or OpenPhish.
"""

